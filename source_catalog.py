def source_topic(exercise_id: int) -> tuple[int, str]:
    for level, (lo, hi, topic) in enumerate(SOURCE_LEVELS, start=1):
        if lo <= exercise_id <= hi:
            return level, topic
    return 10, "Khác"

def source_problem_url(exercise_id: int) -> str:
    code = f"{exercise_id:03d}"
    return f"{SOURCE_SITE}problem/{code}"
